            if (navMenu.classList.contains('active')) {
                toggleIcon.classList.remove('fa-bars');
                toggleIcon.classList.add('fa-xmark');
            } else {
                toggleIcon.classList.remove('fa-xmark');
                toggleIcon.classList.add('fa-bars');
            }
        });

        // Close menu when clicking a nav link (mobile)
        document.querySelectorAll('.nav-links a').forEach(link => {
            link.addEventListener('click', () => {
                navMenu.classList.remove('active');
                toggleIcon.classList.remove('fa-xmark');
                toggleIcon.classList.add('fa-bars');
            });
        });

        // FAQ Accordion Toggle Logic
        const faqItems = document.querySelectorAll('.faq-item');
        faqItems.forEach(item => {
            const questionBtn = item.querySelector('.faq-question');
            questionBtn.addEventListener('click', () => {
                const isActive = item.classList.contains('active');
                faqItems.forEach(i => i.classList.remove('active'));
                if (!isActive) {
                    item.classList.add('active');
                }
            });
        });

        // Savings Calculator Logic
        function updateCalculator() {
            const basketVal = parseFloat(document.getElementById('basket-val').value);
            document.getElementById('basket-val-display').innerText = '£' + basketVal.toFixed(2);

            let hystTotal = basketVal;

            // Third party apps add ~25% product price inflation + ~£3.50 service/small order charge
            let otherPlatformsTotal = (hystTotal * 1.25) + 3.50;
            let totalSaved = otherPlatformsTotal - hystTotal;

            document.getElementById('hyst-price').innerText = '£' + hystTotal.toFixed(2);
            document.getElementById('other-app-price').innerText = '£' + otherPlatformsTotal.toFixed(2);
            document.getElementById('savings-val').innerText = '£' + totalSaved.toFixed(2);
        }

        // Run Calculator on Page Load
        updateCalculator();
