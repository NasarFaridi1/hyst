        // Header Mobile Menu Toggle Script
        const mobileMenuBtn = document.getElementById('mobileMenuBtn');
        const mobileMenu = document.getElementById('mobileMenu');

        if (mobileMenuBtn && mobileMenu) {
            mobileMenuBtn.addEventListener('click', () => {
                mobileMenu.classList.toggle('hidden');
                mobileMenu.classList.toggle('flex');
            });

            // Close mobile menu when a nav link is clicked
            document.querySelectorAll('.mobile-nav-link').forEach(link => {
                link.addEventListener('click', () => {
                    mobileMenu.classList.add('hidden');
                    mobileMenu.classList.remove('flex');
                });
            });
        }

        // 1. Savings & Portion Calculator Script
        const guestRange = document.getElementById('guestRange');
        const guestCountDisplay = document.getElementById('guestCountDisplay');
        const feastType = document.getElementById('feastType');
        const weightResult = document.getElementById('weightResult');
        const sidesResult = document.getElementById('sidesResult');
        const otherCost = document.getElementById('otherCost');
        const hystCost = document.getElementById('hystCost');
        const savingsAmount = document.getElementById('savingsAmount');

        function updateCalculator() {
            const guests = parseInt(guestRange.value);
            guestCountDisplay.innerText = guests + (guests === 1 ? ' Person' : ' People');

            const totalKg = (guests * 0.45).toFixed(1);
            weightResult.innerText = `~ ${totalKg} Kg Fresh Dum Biryani`;
            sidesResult.innerText = `${guests}x Salan & ${guests}x Raita FREE`;

            let pricePerHead = 11.99;
            const selectedFeast = feastType.value;
            if (selectedFeast === 'mutton') pricePerHead = 13.99;
            if (selectedFeast === 'mix') pricePerHead = 16.99;
            if (selectedFeast === 'veg') pricePerHead = 10.49;

            const totalHYST = (guests * pricePerHead).toFixed(2);
            const totalOther = (guests * pricePerHead * 1.35 + 4.50).toFixed(2);
            const saved = (totalOther - totalHYST).toFixed(2);

            otherCost.innerText = `£${totalOther}`;
            hystCost.innerText = `£${totalHYST}`;
            savingsAmount.innerText = `Save £${saved}`;
        }

        if (guestRange && feastType) {
            guestRange.addEventListener('input', updateCalculator);
            feastType.addEventListener('change', updateCalculator);
            updateCalculator();
        }

        function selectSpice(btn) {
            document.querySelectorAll('.spice-btn').forEach(b => {
                b.classList.remove('bg-saffronGold', 'text-nizamMaroon', 'active');
                b.classList.add('text-royalCream');
            });
            btn.classList.add('bg-saffronGold', 'text-nizamMaroon', 'active');
            btn.classList.remove('text-royalCream');
        }

        // 2. Filter Menu Logic
        function filterMenu(category, btn) {
            document.querySelectorAll('.menu-tab').forEach(b => {
                b.classList.remove('bg-saffronGold', 'text-nizamMaroon', 'active');
                b.classList.add('text-royalCream');
            });
            btn.classList.add('bg-saffronGold', 'text-nizamMaroon', 'active');
            btn.classList.remove('text-royalCream');

            const items = document.querySelectorAll('.menu-item');
            items.forEach(item => {
                if (category === 'all') {
                    item.style.display = 'flex';
                } else {
                    if (item.classList.contains(`category-${category}`)) {
                        item.style.display = 'flex';
                    } else {
                        item.style.display = 'none';
                    }
                }
            });
        }

        // 3. FAQ Accordion Toggle Script
        function toggleFaq(button) {
            const content = button.nextElementSibling;
            const icon = button.querySelector('span:last-child');
            const isOpen = content.classList.contains('open');

            document.querySelectorAll('.accordion-content').forEach(c => c.classList.remove('open'));
            document.querySelectorAll('#faqAccordion button span:last-child').forEach(i => i.innerText = '+');

            if (!isOpen) {
                content.classList.add('open');
                icon.innerText = '−';
            }
        }
