        // Other Platforms vs HYST Savings & Price Calculator
        function updateCalculator() {
            const people = parseInt(document.getElementById('people').value);
            const packType = document.getElementById('pack-type').value;

            document.getElementById('people-count').innerText = people;

            let baseHystRate = 4.50; // Base cost per person on HYST
            if (packType === 'qaimaq') baseHystRate = 5.20;
            if (packType === 'squad') baseHystRate = 6.00;

            let hystTotal = (people * baseHystRate);
            if (hystTotal < 9.00) hystTotal = 9.00; // Minimum tub size

            // Other platforms charge ~28% markup + £3.50 service/delivery extra
            let otherPlatformsTotal = (hystTotal * 1.28) + 3.50;
            let totalSaved = otherPlatformsTotal - hystTotal;

            document.getElementById('hyst-price').innerText = '£' + hystTotal.toFixed(2);
            document.getElementById('other-app-price').innerText = '£' + otherPlatformsTotal.toFixed(2);
            document.getElementById('savings-val').innerText = '£' + totalSaved.toFixed(2);
        }

        // Run Calculator on Page Load
        updateCalculator();
